int g_checks = 0, g_failures = 0;

bool expect(bool condition, const char* message) {
    ++g_checks;
    if (!condition) { std::fprintf(stderr, "  FAIL: %s\n", message); ++g_failures; }
    return condition;
}

bool approx(double a, double b, double tol) { return std::abs(a - b) <= tol * (1.0 + std::abs(b)); }

Term T(int var, int delay, double p = 1.0, bool den = false) {
    Term t; t.variable = var; t.delay = delay; t.exponent = p; t.is_denominator = den; return t;
}
Regressor R(std::initializer_list<Term> ts) { Regressor r; r.terms = ts; return r; }

// Multisine-like persistently exciting input.
std::vector<double> make_input(int n, unsigned seed) {
    std::mt19937 g(seed);
    std::uniform_real_distribution<double> u(-1.0, 1.0);
    std::vector<double> x(n);
    for (int k = 0; k < n; ++k) x[k] = 0.6 * std::sin(0.071 * k) + 0.3 * std::sin(0.193 * k + 1.0) + 0.25 * u(g);
    return x;
}

// Row-major (u, y) data generated by a function y(k) = f(u, y, k).
std::vector<double> simulate(int n, const std::vector<double>& u,
                             const std::function<double(const std::vector<double>&, const std::vector<double>&, int)>& f) {
    // y(0..2) are zero initial conditions; y(k) = f(...) for k ≥ 3. The first
    // three rows are dropped so that every returned row satisfies the model.
    const int skip = 3;
    std::vector<double> y(n + skip, 0.0), uu(n + skip, 0.0);
    for (int k = 0; k < n + skip; ++k) uu[k] = u[k % n];
    std::vector<double> d(static_cast<size_t>(n) * 2);
    for (int k = 0; k < n + skip; ++k) {
        if (k >= skip) y[k] = f(uu, y, k);
        if (k >= skip) {
            d[2 * (k - skip)] = uu[k];
            d[2 * (k - skip) + 1] = y[k];
        }
    }
    return d;
}

// ── 1. Normalizer ─────────────────────────────────────────────────────────
bool test_normalizer() {
    std::puts("[normalizer]");
    double train[] = {-2.0, 0.0, 2.0};
    Normalizer mm(NormalizerType::MinMax, -1.0, 1.0);
    mm.fit(train, 3, 1);
    expect(approx(mm.col_norm(0).transform(-2.0), -1.0, 1e-12), "min-max lower endpoint -> -1");
    expect(approx(mm.col_norm(0).transform(2.0), 1.0, 1e-12), "min-max upper endpoint -> 1");
    // P0-3: out-of-range samples must not be clipped and must invert exactly.
    const double out = mm.col_norm(0).transform(6.0);
    expect(approx(out, 3.0, 1e-12), "value outside the training range is mapped linearly (no clipping)");
    expect(approx(mm.inverse_scalar(out, 0), 6.0, 1e-12), "inverse of an extrapolated value is exact");
    double z[] = {-2.0, 0.0, 2.0};
    Normalizer zs(NormalizerType::ZScore);
    zs.fit(z, 3, 1);
    zs.transform(z, 3, 1);
    expect(z[0] < 0.0 && z[2] > 1.0, "z-score is not clamped");
    double c[] = {5.0, 5.0, 5.0};
    Normalizer cn(NormalizerType::MinMax, -1.0, 1.0);
    cn.fit(c, 3, 1);
    expect(approx(cn.col_norm(0).transform(5.0), 0.0, 1e-12), "constant column maps to the centre");
    bool rejected = false;
    try { zs.fit(nullptr, 0, 1); } catch (const std::invalid_argument&) { rejected = true; }
    expect(rejected, "empty training data rejected");
    return true;
}

// ── 2. Power basis ────────────────────────────────────────────────────────
bool test_power_basis() {
    std::puts("[power basis]");
    expect(approx(power_basis(-2.0, 2.0, PowerMode::Hybrid), 4.0, 1e-15), "hybrid: (-2)^2 = 4 (even power is even)");
    expect(approx(power_basis(-2.0, 3.0, PowerMode::Hybrid), -8.0, 1e-15), "hybrid: (-2)^3 = -8");
    expect(approx(power_basis(-4.0, 0.5, PowerMode::Hybrid), -2.0, 1e-15), "hybrid: fractional power is odd extension");
    expect(approx(power_basis(-2.0, 2.0, PowerMode::Signed), -4.0, 1e-15), "signed: sign(x)|x|^2 = -4");
    expect(approx(power_basis(0.0, 1.5, PowerMode::Hybrid), 0.0, 1e-15), "hybrid: 0^1.5 = 0 (no epsilon bias)");
    expect(approx(power_basis(2.0, 1.0, PowerMode::Legacy), 2.000001, 1e-12), "legacy keeps the original epsilon bias");
    expect(approx(quantize_exponent(1.26, 0.5, 3.0, 0.5), 1.5, 1e-15), "exponent quantization to 0.5 grid");
    expect(approx(quantize_exponent(1.26, 0.5, 3.0, 0.0), 1.26, 1e-15), "step 0 keeps exponent continuous");
    return true;
}

// ── 3. QR least squares ───────────────────────────────────────────────────
bool test_qr() {
    std::puts("[qr]");
    // y = 2 a - 3 b + 0.5 with an exactly duplicated column.
    const int m = 50;
    std::vector<double> A(m * 4), y(m);
    std::mt19937 g(1);
    std::normal_distribution<double> nd;
    for (int i = 0; i < m; ++i) {
        const double a = nd(g), b = nd(g);
        A[i * 4 + 0] = a; A[i * 4 + 1] = a; A[i * 4 + 2] = b; A[i * 4 + 3] = 1.0;
        y[i] = 2.0 * a - 3.0 * b + 0.5;
    }
    std::vector<double> x(4);
    int rank = 0;
    expect(qr_solve(A.data(), m, 4, y.data(), x.data(), &rank), "qr_solve succeeds with dependent column");
    expect(rank == 3, "rank 3 detected");
    double sse = 0.0;
    for (int i = 0; i < m; ++i) {
        double p = 0.0;
        for (int j = 0; j < 4; ++j) p += A[i * 4 + j] * x[j];
        sse += (p - y[i]) * (p - y[i]);
    }
    expect(sse < 1e-18, "least-squares residual is zero despite the dependent column (P1-12)");
    expect(approx(x[0] + x[1], 2.0, 1e-10) && approx(x[2], -3.0, 1e-10) && approx(x[3], 0.5, 1e-10),
           "coefficients recovered");
    return true;
}

// ── 4. Exact polynomial identification (even nonlinearity) ────────────────
bool test_polynomial_recovery() {
    std::puts("[polynomial recovery]");
    const int n = 600;
    auto u = make_input(n, 2);
    auto d = simulate(n, u, [](const std::vector<double>& uu, const std::vector<double>& y, int k) {
        return 0.5 * y[k - 1] - 0.2 * y[k - 2] + 0.8 * uu[k - 1] + 0.3 * uu[k - 2] * uu[k - 2] + 0.05;
    });
    Chromosome c;
    c.power_mode = PowerMode::Hybrid;
    c.regressors = {R({T(1, 1)}), R({T(1, 2)}), R({T(0, 1)}), R({T(0, 2, 2.0)})};
    RationalModel m(c);
    expect(m.fit(d.data(), n, 2, 1), "fit succeeds");
    const auto& co = m.chromosome().coefficients;
    expect(approx(co[0], 0.5, 1e-9) && approx(co[1], -0.2, 1e-9) && approx(co[2], 0.8, 1e-9) &&
           approx(co[3], 0.3, 1e-9) && approx(m.chromosome().intercept, 0.05, 1e-9),
           "hybrid basis recovers an even (u^2) term exactly");
    // Free-run of the exact model reproduces the data.
    FreeRunResult fr = m.simulate(d.data(), n, 2, 1);
    double e = 0.0;
    for (size_t i = 0; i < fr.yhat.size(); ++i) e = std::max(e, std::abs(fr.yhat[i] - d[2 * (i + 2) + 1]));
    expect(e < 1e-9 && !fr.diverged, "exact model free-run matches the data");

    // The signed basis cannot represent u^2 exactly.
    Chromosome cs = c;
    cs.power_mode = PowerMode::Signed;
    RationalModel ms(cs);
    ms.fit(d.data(), n, 2, 1);
    auto yh = ms.predict_one_step(d.data(), n, 2, 1);
    double sse = 0.0;
    for (size_t i = 0; i < yh.size(); ++i) sse += std::pow(yh[i] - d[2 * (i + 2) + 1], 2);
    expect(sse > 1e-6, "signed basis (legacy semantics) cannot fit the even term");
    return true;
}

// ── 5. Rational model (pseudo-linearisation is exact without noise) ──────
bool test_rational_recovery() {
    std::puts("[rational recovery]");
    const int n = 600;
    auto u = make_input(n, 3);
    auto d = simulate(n, u, [](const std::vector<double>& uu, const std::vector<double>& y, int k) {
        const double num = 0.6 * y[k - 1] + 0.7 * uu[k - 1];
        const double den = 1.0 + 0.4 * y[k - 1] * y[k - 1];
        return num / den;
    });
    Chromosome c;
    c.regressors = {R({T(1, 1)}), R({T(0, 1)}), R({T(1, 1, 2.0, true)})};
    RationalModel m(c);
    expect(m.fit(d.data(), n, 2, 1), "rational fit succeeds");
    const auto& co = m.chromosome().coefficients;
    expect(approx(co[0], 0.6, 1e-8) && approx(co[1], 0.7, 1e-8) && approx(co[2], 0.4, 1e-8),
           "rational coefficients recovered");
    DenominatorStats st;
    m.predict_one_step(d.data(), n, 2, 1, &st);
    expect(st.sign_changes == 0 && st.min_abs >= 1.0 - 1e-9, "denominator statistics: D >= 1, no sign change");
    return true;
}

// ── 6. Stability diagnostics (P0-2, P0-4) ─────────────────────────────────
bool test_stability() {
    std::puts("[stability]");
    // Well-conditioned denominator: no penalty (the original analyzer penalised it).
    StabilityDiagnostics d;
    d.min_abs_denominator = 0.6;
    StabilityAnalyzer::finalize(d, true);
    expect(d.penalty == 0.0 && d.is_stable, "D = 1 + 0.5 y(k-1) with |D| >= 0.6: no penalty");
    StabilityDiagnostics s;
    s.denominator_sign_changes = 3;
    StabilityAnalyzer::finalize(s, true);
    expect(s.penalty >= 1.0 && !s.is_stable, "denominator crossing zero is penalised");
    StabilityDiagnostics v;
    v.free_run_diverged = true;
    StabilityAnalyzer::finalize(v, false);
    expect(v.penalty == 1.0 && !v.is_stable, "free-run divergence is penalised");

    Chromosome ar;
    ar.regressors = {R({T(1, 1)})};
    ar.coefficients = {1.5};
    expect(approx(StabilityAnalyzer::linear_spectral_radius(ar, 1), 1.5, 1e-9), "spectral radius of y=1.5y(k-1) is 1.5");
    ar.coefficients = {0.5};
    expect(approx(StabilityAnalyzer::linear_spectral_radius(ar, 1), 0.5, 1e-9), "spectral radius of y=0.5y(k-1) is 0.5");
    Chromosome ar2;
    ar2.regressors = {R({T(1, 1)}), R({T(1, 2)})};
    ar2.coefficients = {1.6, -0.8};
    expect(approx(StabilityAnalyzer::linear_spectral_radius(ar2, 1), std::sqrt(0.8), 1e-8),
           "complex pair: radius sqrt(0.8)");

    // Free-run divergence is detected and saturated instead of being masked as 0.
    const int n = 200;
    auto u = make_input(n, 4);
    std::vector<double> data(n * 2);
    for (int k = 0; k < n; ++k) { data[2 * k] = u[k]; data[2 * k + 1] = 0.1 * u[k]; }
    Chromosome div;
    div.regressors = {R({T(1, 1)}), R({T(0, 1)})};
    div.coefficients = {1.5, 1.0};
    div.intercept = 0.0;
    RationalModel dm(div);
    FreeRunResult fr = dm.simulate(data.data(), n, 2, 1, -1, 10.0);
    expect(fr.diverged && fr.divergence_step > 0, "unstable model flagged as divergent");
    bool bounded = true;
    for (double y : fr.yhat) bounded &= std::isfinite(y) && std::abs(y) <= 10.0 + 1e-12;
    expect(bounded, "divergent predictions saturated at the envelope (finite metrics)");
    return true;
}

// ── 7. Evaluator: ERR invariance, metrics, refit flag ─────────────────────
bool test_evaluator() {
    std::puts("[evaluator]");
    const int n = 800, ntr = 560;
    auto u = make_input(n, 5);
    auto d = simulate(n, u, [](const std::vector<double>& uu, const std::vector<double>& y, int k) {
        return 0.7 * y[k - 1] + 0.5 * uu[k - 1] - 0.2 * uu[k - 1] * y[k - 1];
    });
    FitnessWeights w;
    IndividualEvaluator ev(w);
    // Permutation invariance on an inexact structure (an exact fit has
    // SSE at machine precision, where ln(SSE) is pure rounding noise).
    Chromosome p;
    p.regressors = {R({T(1, 1)}), R({T(0, 2)}), R({T(0, 1), T(1, 2)})};
    Chromosome q = p;
    std::swap(q.regressors[0], q.regressors[2]);
    ev.evaluate(p, d.data(), ntr, d.data() + 2 * ntr, n - ntr, 2, 1);
    ev.evaluate(q, d.data(), ntr, d.data() + 2 * ntr, n - ntr, 2, 1);
    expect(p.evaluated && q.evaluated, "both permutations evaluated");
    expect(approx(p.fitness, q.fitness, 1e-9), "fitness invariant to regressor order");
    expect(approx(p.err[0], q.err[2], 1e-9) && approx(p.err[2], q.err[0], 1e-9),
           "ERR invariant to regressor order (greedy FROLS order)");

    Chromosome a;
    a.regressors = {R({T(1, 1)}), R({T(0, 1)}), R({T(0, 1), T(1, 1)})};
    ev.evaluate(a, d.data(), ntr, d.data() + 2 * ntr, n - ntr, 2, 1);
    double s = 0.0;
    for (double e : a.err) s += e;
    expect(s <= 1.0 + 1e-9 && approx(s, a.metrics.r2_train, 1e-6), "sum of centred ERR equals training R^2");
    expect(a.metrics.rmse_val < 1e-9 && a.metrics.rmse_free_run < 1e-6, "exact structure has ~0 validation and free-run error");
    expect(a.metrics.n_val == n - ntr - 1, "validation sample count recorded");

    // refit=false keeps (wrong) coefficients and scores them.
    Chromosome wrong = a;
    wrong.coefficients = {0.0, 0.0, 0.0};
    wrong.intercept = 0.0;
    ev.evaluate(wrong, d.data(), ntr, d.data() + 2 * ntr, n - ntr, 2, 1, false);
    expect(wrong.evaluated && wrong.metrics.rmse_val > 1e-3, "refit=false evaluates the given coefficients");
    expect(ev.evaluations() == 4, "evaluation counter");

    // Diagnose: residual ACF of the exact model is (numerically) white.
    ModelDiagnostics dg = ev.diagnose(a, d.data(), ntr, d.data() + 2 * ntr, n - ntr, 2, 1);
    expect(dg.valid && dg.residual_acf.size() == 21, "residual ACF has lags 0..20");

    // Input contribution (AR terms first): a correct model that contains y(k-1)
    // must not be penalised; a purely autoregressive model has ratio 0.
    expect(a.metrics.input_contribution_ratio > 0.5,
           "input contribution of the true model (with y(k-1)) is high when AR terms enter first");
    Chromosome ar;
    ar.regressors = {R({T(1, 1)}), R({T(1, 2)})};
    ev.evaluate(ar, d.data(), ntr, d.data() + 2 * ntr, n - ntr, 2, 1);
    expect(ar.evaluated && ar.metrics.input_contribution_ratio == 0.0, "purely autoregressive model has ratio 0");
    expect(approx(dg.free_run_rmse_val_full, 0.0, 1e-6), "full validation free-run of the exact model is ~0");
    return true;
}

// ── 8. Canonical form and variation operators (P1-1) ──────────────────────
bool test_operators() {
    std::puts("[operators]");
    Chromosome c;
    c.regressors = {R({T(0, 3, 0.5), T(1, 2), T(0, 3, 1.5)}), R({T(1, 1)}), R({T(1, 1)})};
    expect(c.canonicalize(), "canonicalize reports a change");
    expect(c.num_regressors() == 2 && c.regressors[0].terms.size() == 2,
           "duplicated factor and duplicated regressor removed");

    const int n = 300;
    auto u = make_input(n, 6);
    auto d = simulate(n, u, [](const std::vector<double>& uu, const std::vector<double>& y, int k) {
        return 0.6 * y[k - 1] + 0.4 * uu[k - 1];
    });
    DEConfig cfg;
    cfg.population_size = 8;
    cfg.max_regressors = 8;
    cfg.num_variables = 2;
    cfg.max_delay = 5;
    Island isl(0, cfg, 99, d.data(), 200, d.data() + 400, 100, 2, 1, FitnessWeights());
    Chromosome target, mutant;
    for (int j = 0; j < 6; ++j) target.regressors.push_back(R({T(0, j + 1)}));
    mutant.regressors = {R({T(1, 1)}), R({T(1, 2)})};
    Chromosome trial = isl.crossover_binomial(target, mutant, 1.0);
    expect(trial.num_regressors() == 2, "crossover with CR=1 returns the shorter mutant (models can shrink)");
    Chromosome trial0 = isl.crossover_binomial(target, mutant, 0.0);
    expect(trial0.num_regressors() == 6, "crossover with CR=0 keeps the target length");
    int smaller = 0;
    for (int i = 0; i < 200; ++i) {
        double f, cr;
        Chromosome m = isl.mutate(i % 8, f, cr);
        Chromosome t = isl.crossover_binomial(isl.population()[i % 8], m, cr);
        isl.repair(t);
        if (t.num_regressors() < isl.population()[i % 8].num_regressors()) ++smaller;
    }
    expect(smaller > 0, "trials smaller than the target are generated");
    return true;
}

// ── 9. Optimizer invariants, determinism, tuning side effects (P1-3) ──────
std::vector<double> wh_like_data(int n, unsigned seed) {
    auto u = make_input(n, seed);
    return simulate(n, u, [](const std::vector<double>& uu, const std::vector<double>& y, int k) {
        const double x = 0.8 * uu[k - 1] + 0.2 * uu[k - 2];
        return 0.6 * y[k - 1] - 0.1 * y[k - 2] + 0.5 * std::tanh(1.5 * x);
    });
}

bool test_optimizer() {
    std::puts("[optimizer]");
    const int rows = 500, train = 350;
    auto data = wh_like_data(rows, 7);
    DEConfig cfg;
    cfg.num_islands = 3;
    cfg.population_size = 16;
    cfg.max_regressors = 5;
    cfg.max_terms_per_reg = 2;
    cfg.num_variables = 2;
    cfg.max_delay = 4;
    cfg.max_generations = 12;
    cfg.stagnation_limit = 100;
    cfg.random_seed = 12345;
    cfg.num_threads = 1;

    auto run = [&](int threads, std::vector<double>& best_hist) {
        DEConfig c = cfg;
        c.num_threads = threads;
        DifferentialEvolutionOptimizer opt(c);
        opt.initialize(data.data(), train, data.data() + 2 * train, rows - train, nullptr, 0, 2, 1, FitnessWeights());
        double prev = std::numeric_limits<double>::infinity();
        bool mono = true, finite = true, prob = true;
        int reports = 0;
        opt.run_steps(12, [&](const GenerationReport& r) {
            ++reports;
            finite &= std::isfinite(r.best_fitness);
            prob &= r.success_rate >= 0.0 && r.success_rate <= 1.0;
            mono &= r.best_fitness <= prev + 1e-12;
            prev = r.best_fitness;
            best_hist.push_back(r.best_fitness);
            if (!r.islands.empty()) prob &= static_cast<int>(r.islands.size()) == 3;
        });
        expect(reports == 12, "one report per generation");
        expect(finite, "best fitness finite");
        expect(prob, "success rate in [0,1] and per-island reports present");
        expect(mono, "canonical champion fitness is monotone within a phase");
        expect(opt.is_done() && opt.stop_reason() == "max_generations", "stops at max_generations with reason");
        expect(opt.evaluations() > 12 * 3 * 16, "evaluation counter counts every trial");
        return opt.best_chromosome();
    };
    std::vector<double> h1, h2, h3;
    Chromosome b1 = run(1, h1);
    Chromosome b2 = run(1, h2);
    Chromosome b3 = run(0, h3);
    expect(h1 == h2, "same seed → identical trajectory (sequential)");
    expect(h1 == h3, "parallel islands give the same trajectory as sequential");
    expect(b1.full_hash() == b2.full_hash(), "same seed → identical champion");

    // Tuning CR must not reset the JADE-adapted mean of F.
    DifferentialEvolutionOptimizer opt(cfg);
    opt.initialize(data.data(), train, data.data() + 2 * train, rows - train, nullptr, 0, 2, 1, FitnessWeights());
    opt.run_steps(6, nullptr);
    auto before = opt.island_reports();
    opt.apply_tuning("crossoverRate", 0.3);
    auto after = opt.island_reports();
    bool kept = true, set = true;
    for (size_t i = 0; i < before.size(); ++i) {
        kept &= before[i].mu_f == after[i].mu_f;
        set &= approx(after[i].mu_cr, 0.3, 1e-15);
    }
    expect(kept, "tuning crossoverRate preserves the adapted muF");
    expect(set, "tuning crossoverRate sets muCR");
    expect(!opt.apply_tuning("complexityPenalty", 0.2), "fitness weights are not tunable through the optimizer");

    // Max evaluation budget.
    DEConfig cb = cfg;
    cb.max_generations = 1000;
    cb.max_evaluations = 500;
    DifferentialEvolutionOptimizer ob(cb);
    ob.initialize(data.data(), train, data.data() + 2 * train, rows - train, nullptr, 0, 2, 1, FitnessWeights());
    ob.run_steps(1000, nullptr);
    expect(ob.stop_reason() == "max_evaluations", "maxEvaluations budget stops the run");

    // Polynomial-only search never produces denominators.
    DEConfig cp = cfg;
    cp.denominator_probability = 0.0;
    DifferentialEvolutionOptimizer op(cp);
    op.initialize(data.data(), train, data.data() + 2 * train, rows - train, nullptr, 0, 2, 1, FitnessWeights());
    op.run_steps(5, nullptr);
    expect(!op.best_chromosome().is_rational(), "denominatorProbability=0 yields polynomial models");
    return true;
}

// ── 10. Pruner never worsens the canonical fitness ────────────────────────
bool test_pruner() {
    std::puts("[pruner]");
    const int rows = 500, train = 350;
    auto data = wh_like_data(rows, 8);
    Chromosome c;
    c.regressors = {R({T(1, 1)}), R({T(1, 2)}), R({T(0, 1)}), R({T(0, 3, 2.0)}), R({T(0, 4), T(1, 3)})};
    IndividualEvaluator ev;
    AutomaticPruner pr;
    PruneResult res = pr.prune(c, ev, data.data(), train, data.data() + 2 * train, rows - train, 2, 1);
    expect(res.pruned_chromosome.evaluated, "pruned model evaluated");
    expect(res.fitness_after <= res.fitness_before + 1e-12, "pruning never worsens the fitness");
    expect(res.pruned_chromosome.num_regressors() >= 1, "at least one regressor kept");
    return true;
}

// ── 11. JSON utilities ────────────────────────────────────────────────────
bool test_json() {
    std::puts("[json]");
    json::Value v;
    expect(json::parse("{\"a\":1.5,\"b\":\"x\\\"y\",\"c\":[true,null],\"d\":{\"e\":-2e3}}", v), "parse nested JSON");
    expect(approx(v.number_or("a", 0), 1.5, 0) && v.string_or("b", "") == "x\"y", "numbers and escaped strings");
    expect(v.get("d")->number_or("e", 0) == -2000.0, "nested object");
    expect(!json::parse("{\"a\":}", v), "invalid JSON rejected");
    const std::string s = "{\"r\":" + json::str("quote \" backslash \\ newline \n") + "}";
    expect(json::parse(s, v) && v.string_or("r", "") == "quote \" backslash \\ newline \n", "escape round-trip");
    expect(json::num(std::nan("")) == "null", "NaN serialised as null");
    // Duplicate keys: last one wins (batch overrides).
    expect(json::parse("{\"k\":1,\"k\":2}", v) && v.int_or("k", 0) == 2, "duplicate keys: last wins");
    return true;
}

// ── 12. Model JSON round trip ─────────────────────────────────────────────
bool test_model_io() {
    std::puts("[model io]");
    Chromosome c;
    c.power_mode = PowerMode::Signed;
    c.regressors = {R({T(1, 1)}), R({T(0, 2, 1.5, true)})};
    c.coefficients = {0.25, -0.125};
    c.intercept = 0.01;
    json::Value v;
    expect(json::parse(chromosome_structure_json(c), v), "model JSON parses");
    Chromosome d;
    expect(chromosome_from_json(v, d, PowerMode::Hybrid), "model JSON imports");
    expect(d.power_mode == PowerMode::Signed && d.full_hash() == c.full_hash() &&
           d.coefficients == c.coefficients && d.intercept == c.intercept, "round trip preserves model");
    json::Value bad;
    json::parse("{\"regressors\":[{\"terms\":[{\"variable\":0,\"delay\":0,\"exponent\":1}]}]}", bad);
    Chromosome e;
    expect(!chromosome_from_json(bad, e, PowerMode::Hybrid), "delay 0 rejected");
    return true;
}

