// Phase 0 summary: tabulates experiments/results_phase0/<bench>/e1e2.jsonl and
// evaluates the pre-registered E1/E2 gates (experiments/phase0/PHASE0_PREREG.md).
//
//   dart run tool/experiments/phase0_summary.dart [results_phase0 dir]
//
// Gate population for E2: structures of the main E1 table (variant "lag1");
// the temporal-support controls (variants "rows-1", "rows-1+u0") are reported
// separately. Only validation metrics are read; there are no test metrics in
// these files.
import 'dart:convert';
import 'dart:io';

double? _num(dynamic m, List<String> path) {
  dynamic v = m;
  for (final p in path) {
    if (v is! Map) return null;
    v = v[p];
  }
  return v is num ? v.toDouble() : null;
}

bool _bool(dynamic m, List<String> path) {
  dynamic v = m;
  for (final p in path) {
    if (v is! Map) return false;
    v = v[p];
  }
  return v == true;
}

double _median(List<double> xs) {
  final s = [...xs]..sort();
  if (s.isEmpty) return double.nan;
  final n = s.length;
  return n.isOdd ? s[n ~/ 2] : 0.5 * (s[n ~/ 2 - 1] + s[n ~/ 2]);
}

String _f(double? v, [int d = 4]) => v == null || v.isNaN ? '—' : v.toStringAsFixed(d);

const _executed = {'converged', 'max_iter', 'max_rejects'};

void main(List<String> args) {
  final root = Directory(args.isNotEmpty ? args[0] : 'experiments/results_phase0');
  final out = StringBuffer();
  final gateE1 = <String, bool>{};
  final gateE2 = <String, bool>{};
  out.writeln('# Phase 0: E1/E2 results\n');
  out.writeln('Generated by `tool/experiments/phase0_summary.dart`. RMSE = free-run '
      'simulation RMSE in original units. Validation only; no test data.\n');
  for (final bench in ['cascaded_tanks', 'wiener_hammerstein', 'silverbox']) {
    final f = File('${root.path}/$bench/e1e2.jsonl');
    if (!f.existsSync()) {
      out.writeln('## $bench\n\nNot run yet.\n');
      continue;
    }
    final rows = f
        .readAsLinesSync()
        .where((l) => l.trim().isNotEmpty)
        .map((l) => jsonDecode(l) as Map<String, dynamic>)
        .toList();
    out.writeln('## $bench\n');
    out.writeln('| variant | id | K | zero coef | consistency | train RMSE QR | val RMSE QR | val div QR | '
        'LM status | it | train RMSE LM | val RMSE LM | val div LM | Δval LM/QR |');
    out.writeln('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
    final champVal = <double>[];
    double? pnk40;
    final ratios = <double>[];
    final ratiosAll = <double>[];
    var divQr = 0, divLm = 0, notRun = 0;
    final notRunReasons = <String>[];
    for (final r in rows) {
      final variant = r['variant'] as String? ?? '';
      final id = r['id'] as String? ?? '';
      if (r.containsKey('error')) {
        out.writeln('| $variant | $id | — | — | — | — | — | — | error: ${r['error']} | | | | | |');
        if (variant == 'lag1') {
          notRun++;
          notRunReasons.add('$id: evaluation error');
        }
        continue;
      }
      final vQr = _num(r, ['qr', 'validation', 'rmseFreeRunOrig']);
      final tQr = _num(r, ['qr', 'train', 'rmseFreeRunOrig']);
      final dQr = _bool(r, ['qr', 'validation', 'freeRunDiverged']);
      final lm = r['lm'] as Map<String, dynamic>? ?? {};
      final status = lm['status'] as String? ?? '—';
      final vLm = _num(lm, ['validation', 'rmseFreeRunOrig']);
      final tLm = _num(lm, ['train', 'rmseFreeRunOrig']);
      final dLm = _bool(lm, ['validation', 'freeRunDiverged']);
      final ran = _executed.contains(status) && vQr != null && vLm != null;
      final ratio = ran ? (vLm - vQr) / vQr : null;
      out.writeln('| $variant | $id | ${r['K']} | ${r['zeroCoefficients']} | '
          '${_bool(r, ['consistency', 'ok']) ? 'ok' : 'FAIL'} | ${_f(tQr)} | ${_f(vQr)} | ${dQr ? 'yes' : 'no'} | '
          '$status${lm['reason'] != null ? ' (${lm['reason']})' : ''} | ${lm['iterations'] ?? ''} | ${_f(tLm)} | ${_f(vLm)} | '
          '${ran ? (dLm ? 'yes' : 'no') : '—'} | ${ratio == null ? '—' : '${(100 * ratio).toStringAsFixed(1)} %'} |');
      if (variant == 'lag1') {
        if (r['family'] == 'CHAMP' && vQr != null) champVal.add(vQr);
        if (id == 'PN_K40') pnk40 = vQr;
        if (ran) {
          ratios.add(ratio!);
          if (dQr) divQr++;
          if (dLm) divLm++;
        } else {
          notRun++;
          notRunReasons.add('$id: $status${lm['reason'] != null ? ' (${lm['reason']})' : ''}');
        }
      }
      if (ran) ratiosAll.add(ratio!);
    }
    final vChamp = _median(champVal);
    final e1 = pnk40 != null && !vChamp.isNaN && pnk40 <= 0.90 * vChamp;
    final medRatio = _median(ratios);
    final e2 = !medRatio.isNaN && medRatio <= -0.10 && divLm <= divQr;
    gateE1[bench] = e1;
    gateE2[bench] = e2;
    out.writeln('\n**E1:** V_CHAMP (median validation RMSE of ${champVal.length} distinct champions) = '
        '${_f(vChamp)}; PN_K40 = ${_f(pnk40)}; ratio = ${pnk40 == null || vChamp.isNaN ? '—' : (pnk40 / vChamp).toStringAsFixed(3)} '
        '→ criterion (≤ 0.90): **${e1 ? 'met' : 'not met'}**.\n');
    out.writeln('**E2:** median (V_LM − V_QR)/V_QR over ${ratios.length} executed main-table structures = '
        '${medRatio.isNaN ? '—' : '${(100 * medRatio).toStringAsFixed(1)} %'}; validation divergences QR $divQr, LM $divLm '
        '→ criterion (≤ −10 % and LM divergences ≤ QR): **${e2 ? 'met' : 'not met'}**. '
        'Not executed in the main table: $notRun${notRunReasons.isEmpty ? '' : ' (${notRunReasons.join('; ')})'}. '
        'Including the temporal-support controls: median ${_median(ratiosAll).isNaN ? '—' : '${(100 * _median(ratiosAll)).toStringAsFixed(1)} %'} '
        'over ${ratiosAll.length} (descriptive).\n');
  }
  final nE1 = gateE1.values.where((v) => v).length;
  final nE2 = gateE2.values.where((v) => v).length;
  out.writeln('## Pre-registered gates\n');
  out.writeln('- E1 (capacity): met in $nE1 of ${gateE1.length} benchmarks run → '
      '${gateE1.length < 3 ? 'incomplete (needs all three benchmarks)' : nE1 >= 2 ? '**supported**' : '**not supported**'}.');
  out.writeln('- E2 (simulation-error fitting): met in $nE2 of ${gateE2.length} benchmarks run → '
      '${gateE2.length < 3 ? 'incomplete (needs all three benchmarks)' : nE2 >= 2 ? '**supported**' : '**not supported**'}.');
  final dest = File('${root.path}/SUMMARY_E1E2.md');
  dest.writeAsStringSync(out.toString());
  stdout.write(out.toString());
}
